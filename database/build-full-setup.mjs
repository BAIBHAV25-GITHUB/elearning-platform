#!/usr/bin/env node
// Generates elearning_full_setup.sql from the single sources of truth, so the two can never drift:
//   schema.sql, functions.sql, triggers.sql, views.sql, seed/base_seed.sql, seed/python_course.sql
//
//   node build-full-setup.mjs              write elearning_full_setup.sql
//   node build-full-setup.mjs --no-python  same, without the Python demo course
//   node build-full-setup.mjs --check      exit 1 if the committed file is out of date (used by CI)
//
// Never edit elearning_full_setup.sql by hand. Change the pieces (and add a migration in migrations/
// for databases that already exist), then re-run this script.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.dirname(fileURLToPath(import.meta.url));
const args = new Set(process.argv.slice(2));
const withPython = !args.has('--no-python');
const read = (f) => fs.readFileSync(path.join(dir, f), 'utf8').replace(/\r\n/g, '\n').trimEnd() + '\n';

const banner = (n, title) =>
  `-- ======================================================================\n-- ${n}. ${title}\n-- ======================================================================\n`;

const header = `-- E-Learning Platform: complete database setup (single script)
-- GENERATED by build-full-setup.mjs from schema.sql, functions.sql, triggers.sql, views.sql and seed/*.sql.
-- DO NOT EDIT BY HAND - edit the pieces and re-run the generator.
--
-- Creates the database, schema, functions, triggers, views, base seed data${withPython ? '\n-- and the Python course (52 lessons, each ONE video made of ~10-minute pieces).' : '.'}
--
-- Run ONCE as a superuser, from any database (e.g. "postgres"):
--   psql -U postgres -v ON_ERROR_STOP=1 -f elearning_full_setup.sql
--   (inside SQL Shell:  \\i 'C:/full/path/elearning_full_setup.sql' )
--
-- Requires the psql client (uses \\gexec and \\connect). PostgreSQL 14+.
-- To rebuild from scratch, uncomment the DROP line below (destroys all data).
-- All seeded users share the password:  Password123!
-- DEV / DEMO ONLY: this file contains known passwords. Never run it against production.

-- DROP DATABASE IF EXISTS elearning_db WITH (FORCE);

SELECT 'CREATE DATABASE elearning_db'
 WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = 'elearning_db')\\gexec

\\connect elearning_db
\\set ON_ERROR_STOP on

`;

const parts = [
  header,
  banner(1, 'SCHEMA'), read('schema.sql'), '\n',
  banner(2, 'FUNCTIONS'), read('functions.sql'), '\n',
  banner(3, 'TRIGGERS'), read('triggers.sql'), '\n',
  banner(4, 'VIEWS'), read('views.sql'), '\n',
  banner(5, 'BASE SEED DATA'), read('seed/base_seed.sql'),
];
if (withPython) parts.push('\n', banner(6, 'PYTHON COURSE (demo data)'), read('seed/python_course.sql'));

const out = parts.join('');
const target = path.join(dir, 'elearning_full_setup.sql');

if (args.has('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== out) {
    console.error('elearning_full_setup.sql is out of date. Run: node database/build-full-setup.mjs');
    process.exit(1);
  }
  console.log('elearning_full_setup.sql is up to date.');
} else {
  fs.writeFileSync(target, out);
  console.log(`Wrote ${path.relative(process.cwd(), target)} (${out.split('\n').length} lines)`);
}
